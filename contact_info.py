"""
قبول بيانات التواصل - Contact Info Acceptance (F9)
========================================================================
قبل هذا الملف كانت **أي** رسالة تصل والجلسة `awaiting_contact_info`
تُؤخذ حرفياً كبيانات تواصل وتُنشئ صف حجز. عميلة تكتب «شنو يعني
بالضبط؟» كانت تُسجَّل طلبَ حجز ببيانات تواصل = سؤالها. هذا **تلفيق**
بيانات داخل leads.csv - الملف نفسه الذي تفترض بوابة Gate A أنه جدير
بالثقة - لا مجرد فقدان بيانات.

[القاعدة: عدّ الأرقام، لا شكلها]
الرسالة مقبولة كبيانات تواصل إذا حملت **9 أرقام فأكثر**، بعد ترجمة
الأرقام الهندية العربية إلى ASCII وتجاهل كل ما ليس رقماً (مسافات،
شرطات، أقواس، +، وأي حرف).

القاعدة ضعيفة عمداً. تعبير نمطي مشدود على الشكل العراقي
(`07[3-9]XXXXXXXX`) كان سيرفض:
  - رقماً أرضياً ببغداد (01 + سبعة أرقام)،
  - رقماً خليجياً لعميلة خارج العراق،
  - مدى بادئة يُصدره مشغّل جديد السنة القادمة.
وقاعدةٌ ترفض بيانات تواصل حقيقية أسوأ من الثغرة نفسها: العميلة التي
وصلت إلى هذه المرحلة **وافقت على الحجز بالفعل**، وردّها بسؤال بدل
تأكيد خسارةٌ مباشرة. عدّ الأرقام أضعف اختبار يفصل رقم هاتف عن جملة،
وهو قابل للشرح لعيادة في سطر واحد.

الحد 9 لا 10: الأرقام العراقية المحمولة 11 رقماً، وصيغة 964+ تبلغ
12-13، والأرضي مع مفتاح المدينة 9-10. تحت التسعة لا يوجد رقم تواصل
عراقي صالح.

[ما ترفضه هذه القاعدة خطأً - مذكور لا مكتشَف لاحقاً]
  - رقم مكتوب بالحروف: «صفر سبعة سبعة...».
  - محاولة رقم ناقصة (أقل من 9 أرقام).
كلتاهما تتلقى إعادة سؤال مسجَّلة (contact_info_reprompt.v1) وتكمل بعدها
- لا شيء يسقط بصمت.

[الاسم المبدئي - لماذا لا يكفي عدّ الأرقام وحده]
عميلة كثيرة ترسل اسمها أولاً ثم رقمها في رسالة ثانية. لو رُفضت
الرسالة الأولى ونُسيت، لصار الصف يحمل رقماً بلا اسم - بيانات منقوصة
تعمل عليها العيادة يدوياً. لذلك رسالة **بلا أي رقم** تُحفَظ اسماً
مبدئياً في الجلسة (لا صف، لا حدث، ولا تغيير حالة)، وتُدمَج مع أول
رسالة لاحقة تحمل 9 أرقام فأكثر.

«شنو يعني بالضبط؟» تُحفَظ اسماً مبدئياً كذلك - وهذا مقبول: لا تكتب
شيئاً، ولا تُنشئ حجزاً، ويكتبها فوقها ما ترسله بعدها. التلفيق الذي
تعنيه F9 مغلق سواء.

رسالة تحمل أرقاماً لكن أقل من تسعة ليست اسماً ولا رقماً: محاولة رقم
ناقصة. تتلقى إعادة السؤال ولا تُحفَظ اسماً - كتابتها فوق اسم صحيح
أرسلته قبلها خسارة بلا مقابل.
"""

import matching
import settings

# أقل عدد أرقام يجعل الرسالة بيانات تواصل محتملة - انظر الترويسة.
#
# صار معطى إعداد (config/runtime_config.json تحت contact.min_digits)
# بحدّين مفروضين في الكود: [9، 15]. الحدّ الأدنى ليس تفضيلاً - الترويسة
# أعلاه تثبت أن ما دون التسعة ليس رقم تواصل عراقي، فقيمة أقل تعيد فتح
# F9 وتكتب صفوف حجز ملفّقة. والسقف يمنع خطأ طباعي يرفض كل عميلة صامتاً.
# الافتراضي عند غياب المفتاح 9 نفسها.
MIN_CONTACT_DIGITS = settings.MIN_CONTACT_DIGITS


def count_digits(text: str) -> int:
    """عدد الأرقام في النص، بعد ترجمة الأرقام العربية/الفارسية إلى ASCII."""
    return sum(1 for char in matching.to_ascii_digits(text) if char.isascii() and char.isdigit())


def looks_like_contact_info(text: str) -> bool:
    """هل تحمل الرسالة ما يكفي من الأرقام لتكون بيانات تواصل؟"""
    return count_digits(text) >= MIN_CONTACT_DIGITS


def looks_like_a_name(text: str) -> bool:
    """
    هل تصلح الرسالة اسماً مبدئياً؟ شرط واحد: **لا رقم فيها إطلاقاً**.

    الشرط على الأرقام لا على الحروف عمداً: لا يوجد اختبار يفصل اسماً
    عن سؤال بلا تخمين، والتخمين هنا بلا كلفة - الاسم المبدئي لا يكتب
    شيئاً ويُستبدَل بأي رسالة تالية.
    """
    return bool(text.strip()) and count_digits(text) == 0
