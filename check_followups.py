"""
فحص الاستفسارات المؤهلة للمتابعة (Dry Run - بدون إرسال فعلي)
=================================================================
سكربت مستقل يُشغَّل يدوياً الآن لاختبار منطق الاكتشاف فقط: يطبع في
الطرفية كل استفسار (not_ready) لم تتم متابعته بعد ومرّ عليه الوقت
الكافي - دون إرسال أي رسالة حقيقية.

في هذه الخطوة: عتبة الوقت للاختبار = ساعة واحدة فقط (بدل 48-72
ساعة الفعلية) حتى نستطيع اختباره فوراً دون انتظار أيام.
"""

from leads_store import get_eligible_followups

HOURS_THRESHOLD_FOR_TEST = 1  # للاختبار فقط - سيصبح 48 أو 72 ساعة في الإنتاج

if __name__ == "__main__":
    eligible = get_eligible_followups(HOURS_THRESHOLD_FOR_TEST)

    if not eligible:
        print("لا توجد استفسارات مؤهلة للمتابعة حالياً.")
    else:
        print(f"عدد الاستفسارات المؤهلة للمتابعة: {len(eligible)}\n")
        for row in eligible:
            print(
                f"- العميل: {row['معرف العميل']} | الخدمة: {row['الخدمة المطلوبة']} "
                f"| بتاريخ: {row['التاريخ والوقت']}"
            )