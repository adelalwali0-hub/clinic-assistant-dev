"""
حجب البيانات الشخصية عن مخارج التشخيص (PRD §18 - S12)
========================================================================
S12 كان مفتوحاً لسبب واحد: **صدى الرسائل**. لا طباعة خاصة بالهواتف في
النظام إطلاقاً؛ `message_router` كان يطبع نص كل رسالة واردة، وحين تكون
الجلسة `awaiting_contact_info` فذلك النص **هو** الاسم ورقم الهاتف.
و`outbound` يطبع نص كل رسالة صادرة كذلك، في مسار النجاح ومسار الفشل.

هذا الملف يملك جوابين، ولا يملك غيرهما:
  - `redact(text)`   ماذا يُطبع بدل نص رسالة.
  - `describe_error(e)` ماذا يُطبع بدل رسالة استثناء قد تحمل النص نفسه.

[لماذا لا يكفي حجب النص وحده - رسائل الاستثناءات]
النص لا يتسرّب من موضع الطباعة وحده. `ai_understanding` يضع نص العميلة
**داخل** طلب OpenAI، فرسالة خطأ من مكتبة العميل قد تُعيد جسم الطلب
حرفياً - أي نصها - إلى الطرفية. §18 لا يذكر هذا الموضع، وهو أخطر من
الموضعين اللذين يذكرهما لأنه لا يبدو موضع طباعة أصلاً.

ولهذا معاملان لا معامل واحد: `may_carry_text=True` للطبقات التي مرّرنا
نصها إليها بأيدينا. تلك تُطبع **باسم نوع الاستثناء وحده** افتراضياً.
الباقي يُطبع برسالته، منقّاةً ومقصوصة.

[التنقية غير مشروطة بأي مفتاح]
`requests` يضع الـURL كاملاً في نص استثناء الشبكة، وURL تلغرام يحمل
`TELEGRAM_BOT_TOKEN` بين مقطعين. توكن على stdout ليس بياناً شخصياً بل
مفتاح تحكّم كامل بالبوت، ولا يوجد وضع تشخيص يبرّر كشفه - فالتنقية
تقع دائماً، بصرف النظر عن الصدى.

[لماذا لا مفتاح إعداد لهذا الصدى]
الصدى **لا** يُقرأ من `config/runtime_config.json` ولا من متغير بيئة.
ملف الإعداد هو ما يُنسَخ إلى جهاز التشغيل كما هو، ومتغيّر البيئة يعيش
في `.env` المستثنى من Git - فلا يراه مراجع المستودع مضبوطاً. كلاهما
**أثر يبقى**؛ والمطلوب في S12 تشخيصٌ لا يستطيع أن يبقى.

فالصدى راية سطر أوامر تُكتب بيد المطوّر عند كل تشغيل:

    py -3 main.py --echo-customer-text

`enable_echo()` تُستدعى من كتلة `__main__` في `main.py` وحدها. كل ما
يستورد هذه الوحدة - الاختبارات، `check_followups`, `send_followups`,
التقارير - يجدها مطفأة ولا يملك مساراً لإشعالها. أسوأ ما يبقى: راية في
سطر تشغيل داخل سكربت إقلاع، وهي سطر واحد مرئي في الـdiff.

**هذا يخالف سابقة `USE_AI_INTENT`** (متغيّر بيئة) عن قصد. ذلك مفتاح
سلوك يريد صاحبه أن يدوم؛ وهذا مفتاح يكشف بيانات عميلات، ودوامه هو
العطل نفسه.

[ما لا يغطيه هذا الملف - يُقال ولا يُخفى]
`logging.basicConfig(level=DEBUG)` من أي مكان يجعل `httpx`/`openai`/
`urllib3` تسجّل جسم الطلب المُرسَل إلى OpenAI - وفيه نص العميلة حرفياً،
دون المرور بأي سطر هنا. النظام لا يهيّئ `logging` اليوم إطلاقاً، ولا
مرشِّح جذري يُضاف هنا: مرشِّح على مسجِّل الجذر مهمّة قائمة بذاتها لا
أثر جانبي لهذه. مذكور في D-022.
"""

import re

# أقصى طول لرسالة استثناء تُطبع. جسم خطأ من API قد يبلغ كيلوبايتات،
# وأول مئتَي حرف تحمل السبب عملياً دائماً.
_MAX_ERROR_CHARS = 200

# التوكن في URL تلغرام: `.../bot<التوكن>/sendMessage`. والشكل العاري
# `<أرقام>:<سلسلة>` لأن بعض المكتبات تقتطع الـURL وتُبقي التوكن.
_TOKEN_PATTERNS = (
    re.compile(r"(https?://api\.telegram\.org/bot)[^/\s]+", re.IGNORECASE),
    re.compile(r"\b\d{6,}:[A-Za-z0-9_-]{20,}"),
)

_TOKEN_MASK = "<توكن محجوب>"

# علامة تُرافق كل نص مكشوف. سطر سجل مُلصَق في تذكرة أو محادثة يشي
# بنفسه أن الصدى كان مشتعلاً، فلا يُقرأ سلوكاً افتراضياً.
_ECHO_MARK = "<ECHO!>"

_echo_enabled = False


def enable_echo() -> None:
    """
    يُشعل صدى نصوص العميلات. تُستدعى من `main.py` عند الراية وحدها.

    البانر على stderr لا stdout: مجرى التشخيص لا مجرى التشغيل، ونفس
    اختيار `events.emit` عند الفشل. وهو صريح في أنه ليس وضع تشغيل.
    """
    global _echo_enabled
    _echo_enabled = True
    import sys

    print(
        "\n"
        "  ##############################################################\n"
        "  #  صدى نصوص العميلات مُشتعل (--echo-customer-text).          #\n"
        "  #  أسماء وأرقام هواتف حقيقية ستُطبع في هذه الطرفية.          #\n"
        "  #  للتطوير وحده. لا تُشغَّل هكذا أمام عميلات حقيقيات،         #\n"
        "  #  ولا يُلصَق ناتج هذه الجلسة في تذكرة أو محادثة.             #\n"
        "  ##############################################################\n",
        file=sys.stderr,
    )


def echo_enabled() -> bool:
    return _echo_enabled


def redact(text: str | None) -> str:
    """
    ما يُطبع بدل نص رسالة - واردة أو صادرة.

    البديل ليس `***`: عدّ الأحرف والأرقام يجيب أكثر أسئلة التشخيص بلا
    كشف حرف واحد. عدّ الأرقام تحديداً هو ما يخبر المطوّر أن الرسالة
    «بدت بيانات تواصل» (`contact_info.looks_like_contact_info` يعدّ
    الأرقام نفسها) دون أن يرى الرقم. والصادر يحمل `variant_id` بجواره
    أصلاً، وهو يقود إلى النص الكامل في `variants.py`.
    """
    if text is None:
        return "<لا نص>"
    if _echo_enabled:
        return f"{_ECHO_MARK} {text}"
    digits = sum(1 for ch in text if ch.isdigit())
    return f"<محجوب: {len(text)} حرف، {digits} رقم>"


def scrub_secrets(text: str) -> str:
    """تنقية غير مشروطة: توكن البوت لا يُطبع في أي وضع - انظر الترويسة."""
    for pattern in _TOKEN_PATTERNS:
        text = pattern.sub(
            lambda m: (m.group(1) + _TOKEN_MASK) if m.groups() else _TOKEN_MASK, text
        )
    return text


def describe_error(e: BaseException, may_carry_text: bool = False) -> str:
    """
    ما يُطبع بدل `{e}` في مسار استثناء.

    `may_carry_text=True` للطبقات التي سلّمناها نص العميلة (OpenAI):
    اسم النوع وحده، لأن جسم الخطأ قد يكون طلبنا نفسه معاداً إلينا. مع
    الصدى تُطبع الرسالة كذلك - منقّاةً ومقصوصة كغيرها.

    الافتراضي (`False`) للاستثناءات التي لم يعبرها نص العميلة أصلاً -
    الشبكة والقرص - فرسالتها تُطبع لأن اسم النوع وحده لا يشخّص انقطاعاً.
    """
    name = type(e).__name__
    if may_carry_text and not _echo_enabled:
        return f"{name} (الرسالة محجوبة - قد تحمل نص العميلة)"

    message = scrub_secrets(str(e))
    if len(message) > _MAX_ERROR_CHARS:
        message = message[:_MAX_ERROR_CHARS] + "…"
    return f"{name}: {message}" if message else name
