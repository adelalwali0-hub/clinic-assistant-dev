"""
مسار الإرسال الموحّد - Outbound (PRD D3، F5)
========================================================================
كل رسالة تغادر النظام تمر من `send()` هنا. قبل هذا الملف كان هناك
مساران مستقلان: MessageRouter للردود الحية، وsend_followups.py يتجاوز
الموجّه كلياً ويستدعي `channel.send_message` مباشرة. كل قاعدة تخص
الصادر كان يجب أن تُكتب مرتين، ولم يكن أي صادر قابلاً للربط بنتيجته.

[ما تملكه هذه الدالة]
  - استدعاء القناة وعزل فشلها (استثناء الشبكة لا يصعد للمُستدعي)
  - سطر السجل الطرفي الموحّد ([OUT] / [OUT-FAIL])
  - التحقق من وجود صياغة مسجّلة ([VARIANT-MISSING])
  - إصدار حدث الرسالة الصادرة - **عند النجاح وحده**

[لماذا عند النجاح وحده]
حدث يقول "أُرسلت رسالة" بينما لم تُرسل كذبةٌ لا يكشفها شيء لاحقاً،
وهي بالضبط ما تمنعه ترويسة events.py. الإرسال الفاشل يطبع [OUT-FAIL]
ولا يكتب شيئاً؛ ومسار المتابعة يعيد المحاولة لاحقاً كما كان يفعل
حرفياً، فتُنتج المحاولة الناجحة حدثاً واحداً بالضبط.

[event_type=None: من يملك الحدث]
الافتراضي RESPONSE_SENT - وهو الصحيح لكل رد حي.

مسار المتابعة يمرّر None لأن حدثه (FOLLOWUP_SENT) يجب أن يُكتب داخل
`mark_followup_sent` تحت قفل leads.csv، مباشرة بعد نجاح كتابة الصف:
لو أصدرناه هنا لَوقع الحدث حتى لو فشلت كتابة الصف بعده، فينفصل
"متابعة أُرسلت" في السجل عن "متابعة مُعلَّمة" في الملف - وهو الانفصال
الذي يُنتج إعادة إرسال أبدية بلا أثر يفسّرها.

الرسالة الواحدة تُنتج حدثاً واحداً في الحالتين. النوعان أخوان بمعنى
واحد (رسالة غادرت فعلاً) ويفترقان في المسار - انظر events.py.

[لماذا لا يعبر lead_id إلى القناة]
`lead_id` معامل مستقل هنا ولا يدخل OutgoingMessage. D3 يضع `variant_id`
في الرسالة الصادرة ولا يضع هوية الـLead؛ والقناة يجب ألا ترى أي
معرّف تجاري داخلي. المُرسَل فعلاً إلى Telegram هو `user_id` و`text`
فقط، تماماً كما كان.

[S8] ساعات الإرسال الآمنة - القاعدة هنا، والقرار عند المُستدعي
========================================================================
`is_inside_send_window` هي **الموضع الوحيد** الذي يقرأ الساعة مقابل
النافذة. حلقة المتابعة تستدعيها في كل تكرار لتقرر، و`send` تستدعيها
مرة أخرى قبل لمس القناة. الازدواج مقصود ومقابله معروف من `variant_id`:
عُرفٌ عند موضع القرار، وحارسٌ عند المصبّ.

لماذا لا يكفي أحدهما:
  - المُستدعي وحده لا يكفي - حلقة المتابعة هي كود اليوم. مسار آلي غد
    (تذكير عدم حضور، إعادة تفعيل) يبدأ بلا الفحص، ولا شيء يوقفه.
  - والمصبّ وحده لا يكفي - `send` لا تعرف **لماذا** تُرسل هذه الرسالة،
    ولا تملك ما تفعله بالمؤجَّلة غير إسقاطها. الحلقة وحدها تعرف أن هذا
    الصف ما زال في المرحلة 0 وأنه سيُلتقط في التشغيل التالي.

[is_reply - لماذا الافتراضي يمنع]
S8 يحرس الرسائل التي **يبدؤها النظام**. رد على رسالة وردت قبل ثوانٍ
ليس منها: العميلة التي تكتب الساعة الثالثة فجراً فتحت نافذة خدمتها
بنفسها وهي تنتظر (§19)، وتأجيل ردّها إلى التاسعة يحرق النافذة التي
جاء الحاجز كله ليحسن استعمالها.

والافتراضي `False` - أي «يُحرَس» - لأن اتجاهَي الخطأ ليسا متساويين:
مسار آلي جديد ينسى الراية يُمنع (سلوك آمن ومرئي)، ومسار ردّ جديد
ينسى الراية يتأخر ليلاً (مزعج، ومرئي في السطر، وليس خرقاً لحاجز
سلامة). الافتراضي يقع في الاتجاه الذي يُخطئ نحو الأمان.

[لماذا تُقرأ SEND_WINDOW عند كل نداء]
`settings.SEND_WINDOW` تُقرأ داخل الدالة لا تُثبَّت في وسيط افتراضي:
تثبيتها لحظة الاستيراد هو الفخ نفسه الموصوف في
`test_configured_window_reaches_bound_default_arguments`.

[S6] إيقاف الأتمتة - حارس عند المصبّ
========================================================================
`send` ترفض الإرسال إلى هوية موقوفة ما لم تكن الرسالة **رداً**. هذا
هو المستوى الثاني: المستوى الأول أن الصف الموقوف لا يصير مؤهلاً أصلاً
(`leads_store` في دوال الأهلية الثلاث). الازدواج هو الفرق بين قاعدة
يعرفها كود اليوم وحاجزٍ يصمد أمام مسار آلي يُكتب غداً.

⚠️ ملاحظة على الجار: القسم [S8] أعلاه يصف هذا الازدواج نفسه
(«`send` تستدعيها مرة أخرى قبل لمس القناة»، «حلقة المتابعة تستدعيها في
كل تكرار») - ولا شيء من ذلك موصول في الكود اليوم:
`is_inside_send_window` بلا أي مُستدعٍ. القاعدة مبنية والحاجز غير
نافذ. تُركت كما هي عمداً في هذا التغيير - S8 حاجز آخر ولا يُصلَح
تهريباً داخل حاجز - وتُذكر هنا حتى لا يقرأ أحد وصف S8 دليلاً على أن
S6 موصول بنفس الطريقة. S6 موصول فعلاً؛ الاختبارات تثبت المستويين.

[is_reply هنا - نفس المعامل الذي وصفه S8 ولم يُبنَ]
`is_reply=True` تعني «هذه الرسالة جواب على رسالتها الآن». الإيقاف
يمنع ما **نبدؤه نحن** ولا يمنع جوابها: من كتبت لنا تنتظر رداً، ومن
طلبت التوقف عن المتابعات لم تطلب أن نتجاهلها حين تسأل. حجب الرد كان
سيحوّل حاجزاً يحمي العميلة إلى عقوبة عليها.

والافتراضي `False` - أي «يُحرَس» - لنفس سبب S8 حرفياً: مسار آلي جديد
ينسى الراية يُمنع (آمن ومرئي)، ومسار ردّ جديد ينساها يصمت أمام عميلة
موقوفة (مزعج ومرئي في السطر). الافتراضي يقع في الاتجاه الآمن.
"""

import sys
from datetime import datetime

import events
import privacy
import settings
import variants
from channel_interface import MessagingChannel, OutgoingMessage
from storage import pause_store


def is_inside_send_window(now: datetime | None = None) -> bool:
    """
    هل الساعة الآن داخل نافذة الإرسال الآمنة؟ (S8)

    بلا نافذة مضبوطة: True دائماً - سلوك ما قبل الحاجز حرفياً.

    [بلا مكتبة مناطق زمنية]
    `datetime.now()` محلي بلا منطقة زمنية، نفس اصطلاح `events._now_iso`
    و`leads_store.TIMESTAMP_FORMAT`. بغداد بلا توقيت صيفي، فالوقت
    المحلي الساذج يصف الساعة التي تراها العميلة على هاتفها.

    [النافذة العابرة لمنتصف الليل]
    `from > to` (22:00 → 06:00) شكل صالح يقبله المُتحقِّق، فيُحسب لا
    يُساء قراءته: قراءته بمقارنة واحدة كانت ستُنتج نافذة فارغة صامتة.

    [الحدّان: `from` داخلة و`to` خارجة]
    `to: "21:00"` تعني «نتوقف عند التاسعة»، ورسالة تغادر في 21:00:00
    بالضبط هي رسالة يسمّيها الإنسان «التاسعة مساءً» - وهي الساعة التي
    استثناها المشغّل. الدقيقة تكفي: النافذة تُضبط بـHH:MM، والثواني
    تفصيل لا يعبّر عنه الإعداد أصلاً.
    """
    window = settings.SEND_WINDOW
    if window is None:
        return True

    now = now or datetime.now()
    minutes = now.hour * 60 + now.minute
    start, end = window
    if start < end:
        return start <= minutes < end
    return minutes >= start or minutes < end


def send_window_text() -> str:
    """وصف النافذة للطرفية. للعرض وحده - لا يقرأه أي فرع."""
    window = settings.SEND_WINDOW
    if window is None:
        return "بلا نافذة"
    return f"{window[0] // 60:02d}:{window[0] % 60:02d}-{window[1] // 60:02d}:{window[1] % 60:02d}"


def send(
    channel: MessagingChannel,
    message: OutgoingMessage,
    lead_id: str | None = None,
    event_type: str | None = events.RESPONSE_SENT,
    is_reply: bool = False,
) -> bool:
    """
    يرسل رسالة صادرة واحدة ويسجّلها. يُرجع True عند مغادرة الرسالة
    فعلاً، False عند أي فشل - ولا يرمي استثناءً أبداً.

    lead_id=None (أو "") حالة مشروعة: رسالة أُرسلت قبل وجود أي Lead
    (رد الترحيب بقائمة الخدمات، ورد الخطأ). تُكتب "" في الحدث - أصدق
    من اختلاق معرّف، والحدث يبقى محسوباً ضمن الصادر.

    `is_reply=True` تُعفي الرسالة من حارس S6 - انظر ترويسة الملف.
    """
    # [S6] الحارس **قبل** كل شيء آخر: قبل لمس القناة وقبل أي سطر سجل.
    # الرسالة الممنوعة لم تُرسَل، فلا [OUT] لها ولا حدث - سطر واحد
    # يقول لماذا. الفحص على الهوية لا على lead_id: الإيقاف يخصّ إنساناً،
    # ورسالة بلا lead_id (تحية، رد خطأ) تخصّها كذلك.
    if not is_reply and pause_store.is_paused(channel.channel_name, message.user_id):
        print(f"[PAUSED] -> {message.user_id}: الأتمتة موقوفة لهذه العميلة (S6) - لم تُرسَل")
        return False

    if message.variant_id is None:
        # مرئي لا صامت: رسالة بلا صياغة مسجّلة تخرج فعلاً (إسقاط رسالة
        # عميلة لثغرة محاسبية أسوأ من ثغرة محاسبية)، لكنها لا تمرّ
        # بهدوء. لا مسار إنتاجي اليوم يصل إلى هنا.
        print(
            f"[VARIANT-MISSING] رسالة صادرة بلا variant_id -> {message.user_id}",
            file=sys.stderr,
        )

    try:
        success = channel.send_message(message)
    except Exception as e:
        # لم يعبر نص العميلة هذه الطبقة، فالرسالة تُطبع - انقطاع الشبكة
        # لا يُشخَّص باسم النوع وحده. لكن استثناء `requests` يحمل الـURL
        # كاملاً، وURL تلغرام يحمل التوكن: `scrub_secrets` تنقّيه دائماً.
        print(f"[OUT-FAIL] -> {message.user_id}: فشل الإرسال: {privacy.describe_error(e)}")
        return False

    # [S12] النص الصادر محجوب في الفرعين. `variant_id` بجواره يقود إلى
    # النص الكامل في variants.py، فلا شيء تشخيصي يُفقَد بحجبه.
    if not success:
        print(f"[OUT-FAIL] -> {message.user_id}: {privacy.redact(message.text)}")
        return False

    print(f"[OUT] -> {message.user_id}: {privacy.redact(message.text)} ({message.variant_id})")

    if event_type is not None:
        events.emit(
            event_type,
            lead_id=lead_id or "",
            channel=channel.channel_name,
            variant_id=message.variant_id,
            payload=message_payload(message),
        )

    return True


def message_payload(message: OutgoingMessage) -> dict:
    """
    حمولة حدث رسالة صادرة. نص الرسالة نفسه **لا يُنسَخ** إلى السجل:
    `variant_id` يقود إلى النص في variants.py، ونسخ القالب في كل سطر
    يضخّم ملفاً بالإلحاق فقط بلا فائدة. `variant_hash` بصمة القالب -
    تكشف تعديلاً صامتاً على صياغة مستعمَلة (انظر ترويسة variants.py).
    """
    return {
        "user_id": message.user_id,
        "intent": variants.intent_of(message.variant_id),
        "variant_hash": variants.template_hash(message.variant_id),
    }
