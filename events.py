RESPONSE_SENT = "RESPONSE_SENT"
FOLLOWUP_SENT = "FOLLOWUP_SENT"

# تعديل موثّق على §6 - انظر ترويسة الملف.
LEAD_EXPIRED = "LEAD_EXPIRED"

